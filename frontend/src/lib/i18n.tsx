export const STRINGS: Record<Lang, typeof ro> = { ro, hu };

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: typeof ro;
}

const LanguageContext = createContext<LangCtx>({ lang: "hu", setLang: () => {}, t: hu });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("konsza_lang_pref");
    return saved === "ro" || saved === "hu" ? saved : "hu";
  });
  const setLang = (l: Lang) => {
    localStorage.setItem("konsza_lang_pref", l);
    setLangState(l);
    document.documentElement.lang = l;
  };
  return (
    <LanguageContext.Provider value={{ lang, setLang, t: STRINGS[lang] }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLang = () => useContext(LanguageContext);

export function memberName(t: typeof ro, slug: string): string {
  return t.members.find((m) => m.slug === slug)?.name ?? slug;
}

export function pick(lang: Lang, obj: object, base: string): string {
  return (obj as Record<string, string>)[`${base}_${lang}`] ?? "";
}
